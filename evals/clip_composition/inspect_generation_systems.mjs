import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const evalRoot = path.join(workspaceRoot(), 'evals', 'clip_composition');

function workspaceRoot() {
  let current = process.cwd();
  while (true) {
    if (existsSync(path.join(current, 'pnpm-workspace.yaml'))) {
      return current;
    }
    const parent = path.dirname(current);
    if (parent === current) {
      throw new Error('pnpm-workspace.yaml が見つからないため評価環境の位置を確認できません');
    }
    current = parent;
  }
}

function parseOptions(argv) {
  const values = new Map();
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (!item.startsWith('--')) {
      continue;
    }
    const key = item.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith('--')) {
      values.set(key, 'true');
      continue;
    }
    values.set(key, next);
    index += 1;
  }
  return {
    outputId: String(values.get('outputId') ?? '20260706-v001').replace(/[^a-zA-Z0-9_-]/g, '_')
  };
}

async function findResultFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await findResultFiles(fullPath));
      continue;
    }
    if (entry.isFile() && entry.name === 'result.json') {
      files.push(fullPath);
    }
  }
  return files;
}

function promptNumber(promptVersion) {
  const match = String(promptVersion).match(/v(\d+)$/);
  return match ? Number.parseInt(match[1], 10) : Number.MAX_SAFE_INTEGER;
}

function generationSystemFrom(result, resultPath) {
  const raw = result.generationSystem;
  if (raw && typeof raw.id === 'string' && typeof raw.intervalGenerator === 'string') {
    return { ...raw, legacyInferred: raw.legacyInferred === true };
  }
  const promptVersion = typeof result.promptVersion === 'string' ? result.promptVersion : 'unknown';
  const model = typeof result.model === 'string' ? result.model : '';
  const params = result.params && typeof result.params === 'object' ? result.params : {};
  if (model === 'rule-output-smoke' || model === 'rule-based-result-as-external') {
    return {
      id: 'other-rule-output-score',
      kind: 'other',
      intervalGenerator: 'rule-output-json-rescored-as-external-input',
      promptVersion,
      usesPromptVersionForGeneration: false,
      legacyInferred: true
    };
  }
  if (params.llmCall === false || model === 'rule-based-build_clip_composition' || model === 'baseline-rule') {
    return {
      id: 'baseline-rule',
      kind: 'baseline-rule',
      intervalGenerator: 'runner.buildClipComposition',
      promptVersion: null,
      usesPromptVersionForGeneration: false,
      legacyInferred: true
    };
  }
  if (model.includes('gemini') || model === 'external-prompt-output') {
    return {
      id: `llm-${promptVersion.replace(/^clip_composition_prompt_/, '')}`,
      kind: 'llm',
      intervalGenerator: 'web-gemini+prompt',
      promptVersion,
      usesPromptVersionForGeneration: true,
      legacyInferred: true
    };
  }
  return {
    id: 'other',
    kind: 'other',
    intervalGenerator: typeof result.inputFile === 'string'
      ? `external-json:${path.relative(workspaceRoot(), resultPath)}`
      : `unknown:${path.relative(workspaceRoot(), resultPath)}`,
    promptVersion,
    usesPromptVersionForGeneration: false,
    legacyInferred: true
  };
}

function buildReport(rows, resultPath) {
  const counts = new Map();
  for (const row of rows) {
    counts.set(row.generationSystemId, (counts.get(row.generationSystemId) ?? 0) + 1);
  }
  const lines = [
    '# clip_composition 測定対象の配線図',
    '',
    `- 結果JSON: ${path.relative(evalRoot, resultPath)}`,
    '- 対象: result.json のうち prompt v001〜v006 と baseline-rule',
    '',
    '```mermaid',
    'flowchart LR',
    '  baseline["baseline-rule\\nrunner.buildClipComposition\\nプロンプト版数なし"] --> score["score/result.json"]',
    '  llm["llm-vNNN\\nWeb Gemini + prompt vNNN"] --> score',
    '  other["other\\n外部JSON/旧検証"] --> score',
    '```',
    '',
    '## 件数',
    '',
    '| 生成系統 | 件数 | 区間を実際に生成したもの |',
    '| --- | ---: | --- |'
  ];
  for (const [system, count] of [...counts.entries()].sort(([left], [right]) => left.localeCompare(right))) {
    const generator = rows.find((row) => row.generationSystemId === system)?.intervalGenerator ?? 'unknown';
    lines.push(`| ${system} | ${count} | ${generator} |`);
  }
  lines.push('');
  lines.push('## 対応表');
  lines.push('');
  lines.push('| fixture | prompt label | system | generated by | model | runAt | result |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const row of rows) {
    const legacy = row.legacyInferred ? ' (legacy inferred)' : '';
    lines.push(`| ${row.fixtureId} | ${row.promptVersion} | ${row.generationSystemId}${legacy} | ${row.intervalGenerator} | ${row.model} | ${row.runAt} | ${row.resultPath} |`);
  }
  lines.push('');
  lines.push('## 読み取り');
  lines.push('');
  lines.push('- baseline-rule は、現行ルール処理が固定テーマに対応する発話まとまりから区間を作った結果。prompt labelがv001〜v006でも、区間生成にプロンプト本文は使われていない。');
  lines.push('- llm-vNNN は、Web Geminiへprompt vNNNを渡して生成されたselectedCutsを採点した結果。');
  lines.push('- legacy inferred は、過去のresult.jsonにgenerationSystemフィールドが無いため、model/params/inputFileから推定したもの。');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

async function main() {
  const options = parseOptions(process.argv.slice(2));
  const files = await findResultFiles(path.join(evalRoot, 'outputs'));
  const rows = [];
  for (const file of files) {
    const result = JSON.parse(await readFile(file, 'utf8'));
    const promptVersion = String(result.promptVersion ?? '');
    const promptNo = promptNumber(promptVersion);
    if (promptVersion !== 'baseline-rule' && (promptNo < 1 || promptNo > 6)) {
      continue;
    }
    const generationSystem = generationSystemFrom(result, file);
    rows.push({
      resultPath: path.relative(workspaceRoot(), file),
      fixtureId: String(result.fixtureId ?? 'unknown'),
      promptVersion,
      generationSystemId: String(generationSystem.id),
      intervalGenerator: String(generationSystem.intervalGenerator),
      model: String(result.model ?? 'unknown'),
      runAt: String(result.runAt ?? 'unknown'),
      legacyInferred: generationSystem.legacyInferred === true
    });
  }
  rows.sort((left, right) =>
    left.fixtureId.localeCompare(right.fixtureId) ||
    left.generationSystemId.localeCompare(right.generationSystemId) ||
    promptNumber(left.promptVersion) - promptNumber(right.promptVersion) ||
    left.runAt.localeCompare(right.runAt)
  );
  const outputDir = path.join(evalRoot, 'outputs');
  const reportDir = path.join(evalRoot, 'reports');
  await mkdir(outputDir, { recursive: true });
  await mkdir(reportDir, { recursive: true });
  const resultPath = path.join(outputDir, `generation-system-map-${options.outputId}.json`);
  const reportPath = path.join(reportDir, `generation-system-map-${options.outputId}.md`);
  await writeFile(resultPath, `${JSON.stringify({ kind: 'clip_composition_generation_system_map', runAt: new Date().toISOString(), rows }, null, 2)}\n`, 'utf8');
  await writeFile(reportPath, buildReport(rows, resultPath), 'utf8');
  console.log(`result: ${resultPath}`);
  console.log(`report: ${reportPath}`);
  console.log(`rows: ${rows.length}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
